def case(kind, question, action, answer="", number="ТЕСТ-3821"):
    if kind == "route":
        previous = ["Покажи защиту для спарринга"]
        user = {"вопрос": question, "предыдущие вопросы": previous}
        result = {"action": action, "answer": answer}
        system = ROUTE
    else:
        user = {"сегодня": "2025-05-14", "вопрос": question}
        day = "2025-05-13" if action in {"sales", "purchases"} else ""
        result = {"action": action, "start": day, "end": day,
                  "number": number if action == "order" else "", "year": ""}
        system = PARSE
    return system, json.dumps(user, ensure_ascii=False), result


def training_examples():
    return ([case("route", q, action) for action, questions in ROUTING.items() for q in questions]
            + [case("route", q, "chat", a) for q, a in DIALOG]
            + [case("reports", q, action) for action, questions in REPORTS.items() for q in questions])


def evaluation_examples():
    return [case(kind, q, action, number="ТЕСТ-7342") for kind, action, q in HOLDOUT]
